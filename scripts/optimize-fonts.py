"""Regenerate browser fonts: pip install 'fonttools[woff]==4.66.0'."""
from pathlib import Path
from collections import defaultdict
import json
from fontTools.ttLib import TTFont
from fontTools import subset

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / 'src/assets/fonts'
OUTPUT = FONTS / 'web'
OUTPUT.mkdir(exist_ok=True)
css = ['/* Generated by scripts/optimize-fonts.py. All original Unicode coverage is retained. */']
report = []
generated = set()

def ranges(points):
    result = []
    for cp in sorted(points):
        if result and cp == result[-1][1] + 1:
            result[-1][1] = cp
        else:
            result.append([cp, cp])
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in result)

def rule(family, filename, points=None):
    css.append('\n'.join([
        '@font-face {', f'  font-family: "{family}";',
        '  font-style: normal;', '  font-weight: 400;', '  font-display: swap;',
        f'  src: url("../assets/fonts/web/{filename}") format("woff2");',
        *([f'  unicode-range: {ranges(points)};'] if points else []), '}',
    ]))

# Include the site's own characters in one small first-use font. Unseen names,
# posts, Hanja and other supported scripts are served by disjoint fallback ranges.
ui_points = set(range(256))
for source in sorted((ROOT / 'src').rglob('*')):
    if source.suffix in {'.ts', '.tsx'}:
        ui_points.update(map(ord, source.read_text(encoding='utf-8')))

for original, family, stem in [
    ('NotoSansKR-Regular.otf', 'NotoSansKR', 'noto-sans-kr'),
    ('BMDOHYEON.woff', 'BMDohyeon', 'bm-dohyeon'),
    ('designhouseBold.ttf', 'DesignHouseB', 'designhouse-bold'),
]:
    source = FONTS / original
    with TTFont(source, recalcTimestamp=False) as font:
        coverage = set(font.getBestCmap())
    groups = {}
    if family == 'NotoSansKR':
        groups['ui'] = coverage & ui_points
        extra = defaultdict(set)
        for cp in coverage - groups['ui']:
            key = f'hangul-{cp // 1024:03x}' if 0xAC00 <= cp <= 0xD7AF else f'cjk-{cp // 4096:03x}' if 0x4E00 <= cp <= 0x9FFF else 'other'
            extra[key].add(cp)
        groups.update(dict(sorted(extra.items())))
    else:
        groups['full'] = coverage
    verified = set()
    size = 0
    for group, points in groups.items():
        filename = f'{stem}-{group}.woff2'
        generated.add(filename)
        with TTFont(source, recalcTimestamp=False) as font:
            if family == 'NotoSansKR':
                options = subset.Options()
                options.name_IDs = ['*']
                options.name_legacy = True
                options.name_languages = ['*']
                options.layout_features = ['*']
                options.desubroutinize = True
                sub = subset.Subsetter(options=options)
                sub.populate(unicodes=points)
                sub.subset(font)
            font.flavor = 'woff2'
            font.save(OUTPUT / filename)
        with TTFont(OUTPUT / filename) as encoded:
            actual = set(encoded.getBestCmap())
            assert actual == points, f'Coverage mismatch: {filename}'
            assert not verified & actual, f'Overlapping ranges: {filename}'
            verified |= actual
        size += (OUTPUT / filename).stat().st_size
        rule(family, filename, points if family == 'NotoSansKR' else None)
    assert verified == coverage, f'Lost characters: {family}'
    report.append({'family': family, 'original': source.stat().st_size, 'woff2': size, 'files': len(groups), 'characters': len(coverage)})

(ROOT / 'src/styles/fonts.css').write_text('\n\n'.join(css) + '\n', encoding='utf-8')
for stale in OUTPUT.glob('*.woff2'):
    if stale.name not in generated and stale.name.startswith(('noto-sans-kr-', 'bm-dohyeon-', 'designhouse-bold-')):
        assert stale.resolve().parent == OUTPUT.resolve()
        stale.unlink()
print(json.dumps(report, indent=2))
